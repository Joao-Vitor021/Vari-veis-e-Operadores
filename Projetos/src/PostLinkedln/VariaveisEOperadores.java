package PostLinkedln;

public class VariaveisEOperadores {
	public static void main(String[] args) {
		double n1 = 25;
		double n2 = 5;
		
		System.out.printf("A SOMA entre %.1f e %.1f é igual a %.1f\n", n1, n2, (n1+n2));
		System.out.printf("A SUBTRAÇÃO entre %.1f e %.1f é igual a %.1f\n", n1, n2, (n1-n2));
		System.out.printf("A MULTIPLICAÇÃO entre %.1f e %.1f é igual a %.1f\n", n1, n2, (n1*n2));
		System.out.printf("A DIVISÃO entre %.1f e %.1f é igual a %.1f", n1, n2,n1/n2);
	}

}
